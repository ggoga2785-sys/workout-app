/** Раскладка блинов на одну сторону грифа (жадно, от тяжёлых к лёгким) */
export const PLATES = [25, 20, 15, 10, 5, 2.5, 1.25]

export function platesPerSide(total: number, bar = 20, plates = PLATES) {
  let side = Math.max(0, (total - bar) / 2)
  const out: number[] = []
  for (const p of plates) {
    while (side >= p - 1e-9) { out.push(p); side -= p }
  }
  return { plates: out, rest: Math.round(side * 2 * 100) / 100 }
}

